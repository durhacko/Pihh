/** Lower-left corner of a lit unit cell. x runs right, y runs up (the bottom row of a glyph is y = 0). */
export interface Cell { x: number; y: number }

/**
 * The lit cells of a line of text, in a fixed order: glyph by glyph, top row first, left to right.
 * Lower case is upper-cased; a character without a glyph renders as a space.
 */
export function litCells(text: string): Cell[] {
  const cells: Cell[] = [];
  let pen = 0;
  for (const ch of text.toUpperCase()) {
    const glyph = Object.hasOwn(FONT, ch) ? FONT[ch] : undefined;
    if (glyph !== undefined) {
      for (let row = 0; row < GLYPH_ROWS; row++) {
        const line = glyph[row] ?? '';
        for (let col = 0; col < GLYPH_COLS; col++) {
          if (line[col] === '#') cells.push({ x: pen + col, y: GLYPH_ROWS - 1 - row });
        }
      }
    }
    pen += GLYPH_ADVANCE;
  }
  return cells;
}
